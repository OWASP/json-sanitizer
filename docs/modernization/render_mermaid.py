#!/usr/bin/env python3
"""Write call-graph.mmd, data-lineage.mmd and critical-path.mmd from topology.json.

Each stays under ~40 edges: the call graph and the data lineage are collapsed to
domain level (the method graph has 76 call/dispatch and 45 read/write edges).
"""
import json, os, re
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
t = json.load(open(os.path.join(HERE, "topology.json")))
dom_of, name, kind = {}, {}, {}
for d in t["root"]["children"]:
    for l in d["children"]:
        dom_of[l["id"]], name[l["id"]], kind[l["id"]] = d["id"], l["name"], l["kind"]
dname = {d["id"]: d["name"] for d in t["root"]["children"]}
mid = lambda s: re.sub(r"\W", "_", s)
q = lambda s: '"' + s.replace('"', "'").replace("<", "&lt;").replace(">", "&gt;") + '"'

# ---- call graph (domain level)
entry_doms = Counter(dom_of[e] for e in t["entryPoints"])
c = Counter((dom_of[e["source"]], dom_of[e["target"]]) for e in t["edges"]
            if e["kind"] in ("call", "dispatch") and dom_of[e["source"]] != dom_of[e["target"]])
out = ["%% json-sanitizer: domain-level call graph (method edges collapsed; label = edge count)",
       "%% generated by render_mermaid.py from topology.json", "graph TD"]
for d in t["root"]["children"]:
    if d["id"] == "dom:data":
        continue
    n = entry_doms.get(d["id"])
    out.append(f"  {mid(d['id'])}[{q(d['name'] + (f' — {n} entry point(s)' if n else ''))}]")
for (a, b), n in sorted(c.items()):
    out.append(f"  {mid(a)} -->|{n}| {mid(b)}")
out += ["  classDef entry fill:#fde68a,stroke:#b45309,stroke-width:2px"]
out += [f"  class {mid(d)} entry" for d in entry_doms]
open(os.path.join(HERE, "call-graph.mmd"), "w").write("\n".join(out) + "\n")
print(f"call-graph.mmd: {len(c)} edges")

# ---- data lineage (domain -> store, read vs write)
rw = Counter((dom_of[e["source"]], e["target"], e["kind"]) for e in t["edges"] if e["kind"] in ("read", "write"))
out = ["%% json-sanitizer: data lineage, domains to in-memory stores and caller I/O",
       "%% solid = write, dotted = read; label = number of methods", "graph LR"]
for d in sorted({k[0] for k in rw}):
    out.append(f"  {mid(d)}[{q(dname[d])}]")
for s in sorted({k[1] for k in rw}):
    out.append(f"  {mid(s)}[({q(name[s])})]")
for (d, s, k), n in sorted(rw.items()):
    out.append(f"  {mid(d)} ==>|write {n}| {mid(s)}" if k == "write" else f"  {mid(s)} -.->|read {n}| {mid(d)}")
open(os.path.join(HERE, "data-lineage.mmd"), "w").write("\n".join(out) + "\n")
print(f"data-lineage.mmd: {len(rw)} edges")

# ---- critical path: the primary persona flow
f = t["flows"][0]
out = [f"%% critical path: {f['name']} ({f['persona']})",
       "%% no telemetry was available (ASSESSMENT: library, no APM), so no p50/p99;",
       "%% measured worst case: SEC-001, 1M hex digits ~26 s in normalizeNumber", "flowchart TD"]
prev = None
for i, s in enumerate(f["steps"], 1):
    nodes = ", ".join(name[n].replace("JsonSanitizer.", "") for n in s["nodes"])
    out.append(f"  S{i}[{q(f'{i}. ' + s['label'] + ' — ' + nodes)}]")
    if prev:
        out.append(f"  {prev} --> S{i}")
    prev = f"S{i}"
hot = next(i for i, s in enumerate(f["steps"], 1) if "JsonSanitizer#normalizeNumber" in s["nodes"])
out += ["  classDef hot fill:#fecaca,stroke:#b91c1c,stroke-width:2px", f"  class S{hot} hot"]
open(os.path.join(HERE, "critical-path.mmd"), "w").write("\n".join(out) + "\n")
print(f"critical-path.mmd: {len(f['steps']) - 1} edges")
